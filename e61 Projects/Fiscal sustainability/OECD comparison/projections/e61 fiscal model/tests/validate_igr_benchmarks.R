args<-commandArgs(FALSE);script<-sub('^--file=','',args[grepl('^--file=',args)][1])
setwd(normalizePath(file.path(dirname(script),'..'),mustWork=TRUE))
source('R/model.R');x<-load_inputs();cal<-calibrate(x);b<-project_model(x,default_assumptions(),cal)
o<-read.csv('data/processed/igr_spending_benchmarks.csv');notes<-igr_spending_notes();checks<-0L
check<-function(z){stopifnot(z);checks<<-checks+1L}
check(setequal(names(notes),cal$programmes$programme))
check(!anyDuplicated(o[c('programme','year')]))
check(!'Other public services'%in%o$programme)
check(all(subset(o,programme=='Defence')$igr_pct==c(2.4,2.5,2.5,2.5)))
old<-read.csv('data/processed/ndis_igr_benchmark.csv');nd<-subset(o,programme=='NDIS')
check(all(nd$igr_pct==old$igr_2026_pct[match(nd$year,old$year)]))
expected<-c(Health=6.2,Education=1.1,'Age Pension'=1.8,'Aged care'=2.3,NDIS=2,'Other social protection'=2.6,Defence=2.5)
for(p in names(notes)){
 d<-igr_spending_comparison(b,b,o,p)
 check(all(d$scenario_pct==d$reference_pct))
 check(isTRUE(all.equal(d$scenario_bn,b$components$spending_bn[match(paste(p,d$year),paste(b$components$programme,b$components$year))])))
 if(p%in%names(expected))check(abs(d$igr_pct[d$year==2066]-expected[p])<1e-8)
 else check(all(is.na(d$igr_pct)))
 check(nzchar(igr_spending_summary(b,o,p)))
 check(ncol(format_igr_spending_table(d,p))==5)
}
def<-igr_spending_comparison(b,b,o,'Defence')
check(all(is.na(def$igr_pct[def$year%in%c(2030,2035,2050)])))
a<-default_assumptions();a$health_cost_growth_adjustment<-.01;s<-project_model(x,a,cal)
changed<-igr_spending_comparison(s,b,o,'Health');base<-igr_spending_comparison(b,b,o,'Health')
check(tail(changed$scenario_pct,1)>tail(base$scenario_pct,1))
check(identical(changed$igr_pct,base$igr_pct)&&identical(changed$reference_pct,base$reference_pct))
check(grepl('2036-2066',igr_spending_summary(b,o,'Defence'),fixed=TRUE))
cat(checks,'IGR comparison checks passed.\n')
